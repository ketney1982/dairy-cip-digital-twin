function summary = build_model_equation_summary()
%BUILD_MODEL_EQUATION_SUMMARY  Machine-readable summary of the CIP twin's model.
%
%   summary = BUILD_MODEL_EQUATION_SUMMARY() writes results/model_equation_summary.json
%   describing, in TEXT form, the governing equations of the Simulink digital
%   twin (model/dairy_cip_digital_twin.slx as constructed by build_model.m), the
%   empirical constants (read live from cip_model_params, the single source of
%   truth), the input ranges, the output definitions, the model's declared
%   limitations, and the EXPECTED qualitative relations between inputs and
%   outputs (with a review status per relation).
%
%   This summary is the structured context consumed by gemini_model_auditor. It
%   does NOT modify the model or any parameter. All numbers describe a
%   SIMULATION-GENERATED SYNTHETIC, proof-of-concept model - not a calibrated one.
%
%   See also: GEMINI_MODEL_AUDITOR, CIP_MODEL_PARAMS, BUILD_MODEL.

    here = fileparts(mfilename('fullpath'));
    root = fileparts(here);
    addpath(here);
    resDir = fullfile(root,'results'); if ~exist(resDir,'dir'); mkdir(resDir); end
    outPath = fullfile(resDir,'model_equation_summary.json');

    P = cip_parameters();
    M = cip_model_params();          % single source of truth for the numbers

    summary = struct();
    summary.model_name = P.model_name;
    summary.data_label = 'simulation-generated synthetic data - NOT real industrial data';
    summary.disclaimer = ['Proof-of-concept mechanistic model with uncalibrated ', ...
        'coefficients. Equations and constants must be re-estimated from plant or ', ...
        'literature data before any scientific or operational claim.'];
    summary.description = ['Four-phase dairy CIP cycle (pre-rinse -> alkaline wash ', ...
        '-> intermediate rinse -> final rinse) with first-order soil-removal ', ...
        'kinetics and separated visual subsystems for water, thermal energy, pump ', ...
        'energy, wastewater/COD, hygiene/risk, EHPI/output metrics and logging. ', ...
        'Phase scheduling is provided by a Stateflow chart when available, with ', ...
        'a MATLAB Function fallback. All empirical constants are read from ', ...
        'cip_model_params.'];
    summary.model_architecture = struct( ...
        'top_level_subsystems', {{ ...
            'Scenario Inputs', ...
            'Phase Scheduler', ...
            'Soil Removal Kinetics', ...
            'Water Consumption', ...
            'Thermal Energy', ...
            'Pump Energy', ...
            'Wastewater and COD', ...
            'Hygiene and Risk', ...
            'EHPI and Output Metrics', ...
            'Logging and Scopes'}}, ...
        'scenario_parameter_exposure', ['Constant blocks in Scenario Inputs use ', ...
            'editable variable names overridden per run by Simulink.SimulationInput.setVariable ', ...
            'in the model workspace.'], ...
        'workspace_policy', 'No base-workspace assignin and no globals; scenario injection uses SimulationInput.');
    summary.logged_signals = P.logged_signals;

    % ---- Phases ---------------------------------------------------------
    summary.phases = struct( ...
        'phase_1','pre-rinse','phase_2','alkaline wash', ...
        'phase_3','intermediate rinse','phase_4','final rinse', ...
        'phase_5','end/idle', ...
        'scheduling','time-driven by cumulative durations t_pre, t_alk, t_int, t_final');

    % ---- Governing equations (textual; match build_model.m exactly) -----
    eq = struct();
    eq.soil_state_ode = 'dsoil/dt = -k(phase) * max(soil,0)';
    eq.k_pre   = 'k = k_cal * k_pre_base * (Q_m3h/Q_ref)^beta_Q                                   [pre-rinse]';
    eq.k_alk   = 'k = k_cal * k_alk_base * exp(alpha_T*(T_C - T_ref)) * (Q_m3h/Q_ref)^beta_Q * (NaOH_pct/NaOH_ref)^gamma_NaOH   [alkaline]';
    eq.k_rinse = 'k = k_cal * k_rinse_base * (Q_m3h/Q_ref)^beta_Q                                 [intermediate & final rinse]';
    eq.k_idle  = 'k = 0                                                                           [end/idle]';
    eq.cod_organic = 'COD_mgL = COD_factor * max(soil0 - soil,0), where soil0 - soil is cumulative soil removed';
    eq.naoh_residual = 'NaOH_res = NaOH_pct * {10000 alk; 1500 int; 300 final; 0 otherwise}  [mg/L]';
    eq.cod_instant = 'COD_inst is no longer used as the reported organic COD; the reported COD is cumulative-soil based';
    eq.cod_reported = 'COD_mgL is an organic-load proxy and deliberately excludes inorganic NaOH residual';
    eq.naoh_reported = 'NaOH_residual_mgL = time_integral(NaOH_res)/t_cycle  (cycle time-average)';
    eq.cod_chemical_equivalent = 'COD_chem_equiv_mgL = COD_chemical_factor * NaOH_residual_mgL, reported separately from COD_mgL';
    eq.water = 'water_L_s = (Q_m3h*1000/3600) * (1 - water_rec)  during active phases; integrated to water_L';
    eq.thermal = 'thermal_kW = (rho*(Q_m3h/3600)*cp*max(T_C - T_in_C,0)/eta_heater) * (1 - heat_rec)   [alkaline wash only]; integrated to thermal_energy_kWh';
    eq.pump = 'pump_kW = (deltaP*(Q_m3h/3600)/eta_pump)/1000  during active phases; integrated to pump_energy_kWh';
    eq.total_energy = 'total_energy_kWh = thermal_energy_kWh + pump_energy_kWh';
    eq.co2 = 'CO2eq_kg = thermal_energy_kWh*EF_thermal + pump_energy_kWh*EF_electricity';
    eq.cleaning = 'cleaning_score = clamp((1 - soil)*100, 0, 100)   [%]';
    eq.hygienic_risk = 'hygienic_risk = clamp(soil / soil_risk_ref, 0, 1)';
    eq.ehpi = 'EHPI = 100 * (cleaning_score/100) / (1 + 0.25*(water_L/norm_water_L + total_energy_kWh/norm_energy_kWh + COD_mgL/norm_COD_mgL + CO2eq_kg/norm_CO2eq_kg))';
    summary.equations = eq;

    % ---- Constants (live, from cip_model_params) ------------------------
    summary.parameters = M;
    summary.parameter_source = 'src/cip_model_params.m (single source of truth)';

    % ---- Input ranges ---------------------------------------------------
    units = struct('T_C','degC','Q_m3h','m3/h','t_pre','s','t_alk','s','t_int','s', ...
                   't_final','s','NaOH_pct','%','soil0','-','heat_rec','-','water_rec','-');
    inRanges = struct([]);
    for k = 1:numel(P.var_names)
        nm = P.var_names{k};
        role = 'operator_setpoint';
        if strcmp(nm,'soil0'); role = 'uncertainty_condition'; end
        u = '-'; if isfield(units,nm); u = units.(nm); end
        s = struct('name',nm,'lb',P.lb(k),'ub',P.ub(k),'unit',u,'role',role);
        if isempty(inRanges); inRanges = s; else; inRanges(end+1) = s; end %#ok<AGROW>
    end
    summary.input_ranges = inRanges;
    summary.fixed_inputs = struct('T_in_C', M.T_in_C);

    % ---- Output definitions ---------------------------------------------
    outDefs = { ...
        'water_L','L','per-cycle fresh water consumption'; ...
        'thermal_energy_kWh','kWh','per-cycle heating energy (alkaline wash)'; ...
        'pump_energy_kWh','kWh','per-cycle pumping energy'; ...
        'total_energy_kWh','kWh','thermal + pump energy'; ...
        'COD_mgL','mg/L','organic-load proxy from cumulative soil removed; excludes inorganic NaOH residual'; ...
        'NaOH_residual_mgL','mg/L','cycle time-averaged NaOH residual'; ...
        'CO2eq_kg','kg','per-cycle CO2-equivalent emissions'; ...
        'cleaning_score','%','100*(1-residual soil); model-derived hygiene proxy (NOT microbiological)'; ...
        'hygienic_risk','-','residual-soil risk proxy in [0,1]'; ...
        'EHPI','-','proposed Environmental-Hygienic Performance Index (NOT a standard)'};
    od = struct([]);
    for i = 1:size(outDefs,1)
        s = struct('name',outDefs{i,1},'unit',outDefs{i,2},'definition',outDefs{i,3});
        if isempty(od); od = s; else; od(end+1) = s; end %#ok<AGROW>
    end
    summary.output_definitions = od;

    % ---- Expected qualitative relations (for the auditor) ---------------
    rel = {};
    rel{end+1} = localRel('T_C','total_energy_kWh','positive','expected_and_consistent', ...
        'Thermal power rises with (T_C - T_in_C), so higher setpoint increases energy.');
    rel{end+1} = localRel('T_C','cleaning_score','positive','expected_and_consistent', ...
        'Alkaline rate constant scales with exp(alpha_T*(T_C - T_ref)).');
    rel{end+1} = localRel('water_rec','water_L','negative','expected_and_consistent', ...
        'Water flow is scaled by (1 - water_rec).');
    rel{end+1} = localRel('heat_rec','total_energy_kWh','negative','expected_and_consistent', ...
        'Thermal power is scaled by (1 - heat_rec).');
    rel{end+1} = localRel('heat_rec','CO2eq_kg','negative','expected_and_consistent', ...
        'CO2eq is dominated by thermal energy, which falls with heat_rec.');
    rel{end+1} = localRel('NaOH_pct','cleaning_score','positive','expected_and_consistent', ...
        'Alkaline rate scales with (NaOH_pct/NaOH_ref)^gamma_NaOH.');
    rel{end+1} = localRel('t_alk','cleaning_score','positive','expected_and_consistent', ...
        'Longer alkaline phase removes more soil under first-order kinetics.');
    rel{end+1} = localRel('soil0','cleaning_score','negative','expected_and_consistent', ...
        'Higher initial soil leaves more residual soil at finite kinetics.');
    rel{end+1} = localRel('soil0','COD_mgL','positive','expected_and_consistent', ...
        ['Organic COD is now based on cumulative soil removed, so larger initial ', ...
         'soil loads should increase COD_mgL when a finite fraction is removed.']);
    rel{end+1} = localRel('NaOH_pct','COD_mgL','weak_or_indirect','expected_and_consistent', ...
        ['NaOH_pct can affect COD_mgL indirectly through alkaline soil-removal ', ...
         'kinetics, but inorganic NaOH residual is not added to COD_mgL. It is ', ...
         'reported separately as NaOH_residual_mgL and COD_chem_equiv_mgL.']);
    summary.expected_relations = [rel{:}];

    % ---- Declared limitations -------------------------------------------
    summary.declared_limitations = { ...
        'Uncalibrated proof-of-concept coefficients (k_cal is a tuning knob).'; ...
        'COD chemistry is simplified: COD_mgL is an organic proxy from cumulative soil removed.'; ...
        'NaOH residual is reported separately and is not folded into COD_mgL.'; ...
        'cleaning_score is a soil-based proxy, NOT a microbiological/ATP measurement.'; ...
        'EHPI is a proposed index with ad-hoc weights and normalization, not a standard.'; ...
        'Thermal energy is modelled for the alkaline wash only (MVP).'; ...
        'No wastewater-treatment, no full LCA boundary, no real sensor noise.'};

    % ---- Write ----------------------------------------------------------
    fid = fopen(outPath,'w');
    if fid < 0; error('build_model_equation_summary:fopen','Cannot write %s', outPath); end
    fwrite(fid, jsonencode(summary,'PrettyPrint',true), 'char'); fclose(fid);
    fprintf('[build_model_equation_summary] %d relations, %d params -> %s\n', ...
        numel(summary.expected_relations), numel(fieldnames(M)), outPath);
end

% ======================================================================
function r = localRel(driver, target, expected_sign, status, rationale)
    r = struct('driver',driver,'target',target,'expected_sign',expected_sign, ...
        'review_status',status,'rationale',rationale);
end

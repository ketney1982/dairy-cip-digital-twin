function out = cip_policy_profiles(name)
%CIP_POLICY_PROFILES  Canonical operational policy profiles for the CIP study.
%
%   P = CIP_POLICY_PROFILES() returns a struct array with ALL profiles.
%   P = CIP_POLICY_PROFILES(name) returns the single profile whose .profile
%       field matches `name` (case-insensitive); errors if unknown.
%
%   These profiles are the SINGLE SOURCE OF TRUTH shared by
%   gemini_policy_translator.m (mock + Gemini seeding) and run_policy_portfolio.m
%   so the same managerial/regulatory contexts are described identically
%   everywhere. Each profile has the fields:
%       .profile            canonical key (one of the six below)
%       .policy_name        human-readable label
%       .policy_text        natural-language description (fed to Gemini / mock)
%       .constraints        struct with the SIX limit fields. A limit of NaN
%                           means "no cap" and is encoded to JSON null (never []).
%                           Fields: min_cleaning_score, max_COD_mgL,
%                           max_hygienic_risk, max_water_L,
%                           max_total_energy_kWh, max_CO2eq_kg
%       .objective_weights  struct of FIVE weights (sum == 1): water_L,
%                           total_energy_kWh, COD_mgL, CO2eq_kg, cleaning_score.
%                           hygienic_risk is deliberately NOT an objective weight:
%                           within the feasible region (cleaning_score >= 95, i.e.
%                           soil <= soil_risk_ref) hygienic_risk = soil/soil_risk_ref
%                           is an affine function of cleaning_score (= (1-soil)*100),
%                           so weighting it would merely double-count cleaning. It
%                           is enforced instead as the hard cap max_hygienic_risk.
%       .risk_tolerance     'low' | 'medium' | 'high'
%
%   ---------------------------------------------------------------------------
%   The numeric caps and weights are PROOF-OF-CONCEPT ASSUMPTIONS for a study on
%   SIMULATION-GENERATED SYNTHETIC DATA. They are NOT regulatory thresholds and
%   must be replaced with jurisdiction-specific limits before any real use.
%   ---------------------------------------------------------------------------
%
%   See also: GEMINI_POLICY_TRANSLATOR, RUN_POLICY_PORTFOLIO.

    P = struct([]);

    P = localAdd(P, 'balanced_default', ...
        'Balanced default operation', ...
        ['No single environmental burden dominates. Maintain the hygiene floor ', ...
         'and minimise water, energy, COD and CO2 in a balanced way.'], ...
        struct('min_cleaning_score',95,'max_COD_mgL',NaN,'max_hygienic_risk',NaN, ...
               'max_water_L',NaN,'max_total_energy_kWh',NaN,'max_CO2eq_kg',NaN), ...
        [0.20 0.20 0.20 0.20 0.10], 'medium');

    P = localAdd(P, 'water_scarcity', ...
        'Regional water-scarcity restriction', ...
        ['A regional drought restricts process water. Strongly prioritise low ', ...
         'water consumption per CIP cycle while keeping the hygiene floor.'], ...
        struct('min_cleaning_score',95,'max_COD_mgL',NaN,'max_hygienic_risk',NaN, ...
               'max_water_L',600,'max_total_energy_kWh',NaN,'max_CO2eq_kg',NaN), ...
        [0.40 0.10 0.15 0.10 0.15], 'low');

    P = localAdd(P, 'energy_price_spike', ...
        'Energy price spike', ...
        ['Electricity and heat prices have spiked. Prioritise low total energy ', ...
         'use (thermal + pump) and lower CO2, tolerating moderate water use.'], ...
        struct('min_cleaning_score',95,'max_COD_mgL',NaN,'max_hygienic_risk',NaN, ...
               'max_water_L',NaN,'max_total_energy_kWh',20,'max_CO2eq_kg',NaN), ...
        [0.10 0.40 0.10 0.20 0.10], 'medium');

    P = localAdd(P, 'cod_discharge_limit', ...
        'Stricter COD discharge limit', ...
        ['The wastewater permit tightened the allowable COD concentration. ', ...
         'Prioritise low effluent COD and respect a hard COD cap.'], ...
        struct('min_cleaning_score',95,'max_COD_mgL',700,'max_hygienic_risk',NaN, ...
               'max_water_L',NaN,'max_total_energy_kWh',NaN,'max_CO2eq_kg',NaN), ...
        [0.15 0.10 0.40 0.10 0.15], 'low');

    P = localAdd(P, 'carbon_reduction', ...
        'Corporate carbon-reduction target', ...
        ['A corporate decarbonisation target applies. Prioritise low CO2eq, ', ...
         'favouring heat recovery and energy efficiency.'], ...
        struct('min_cleaning_score',95,'max_COD_mgL',NaN,'max_hygienic_risk',NaN, ...
               'max_water_L',NaN,'max_total_energy_kWh',NaN,'max_CO2eq_kg',4.0), ...
        [0.10 0.25 0.10 0.35 0.10], 'medium');

    P = localAdd(P, 'hygiene_priority', ...
        'Elevated hygiene priority', ...
        ['A high-risk product run requires elevated hygiene assurance. Raise the ', ...
         'cleaning floor and constrain residual-soil hygienic risk; environmental ', ...
         'burdens are secondary.'], ...
        struct('min_cleaning_score',98,'max_COD_mgL',NaN,'max_hygienic_risk',0.10, ...
               'max_water_L',NaN,'max_total_energy_kWh',NaN,'max_CO2eq_kg',NaN), ...
        [0.10 0.10 0.15 0.10 0.55], 'low');

    if nargin >= 1 && ~isempty(name)
        idx = find(strcmpi({P.profile}, char(name)), 1);
        if isempty(idx)
            error('cip_policy_profiles:unknown', ...
                'Unknown policy profile "%s". Known: %s', ...
                char(name), strjoin({P.profile}, ', '));
        end
        out = P(idx);
    else
        out = P;
    end
end

% ======================================================================
function P = localAdd(P, key, label, text, constraints, w, risk)
% Append one fully-formed profile, normalising the 5 weights to sum to 1.
    w = max(0, w(:).');
    if sum(w) <= 0; w = ones(1,5); end
    w = w / sum(w);
    % Round the first four and set the last as the remainder so the five weights
    % sum to EXACTLY 1.0 (no 0.9999 rounding drift in the saved JSON).
    r = round(w(1:4), 4);
    ow = struct('water_L',r(1),'total_energy_kWh',r(2), ...
                'COD_mgL',r(3),'CO2eq_kg',r(4), ...
                'cleaning_score', round(1 - sum(r), 4));
    % Governance floor: cleaning score may never be set below 95.
    constraints.min_cleaning_score = max(95, constraints.min_cleaning_score);
    s = struct('profile',key,'policy_name',label,'policy_text',text, ...
               'constraints',constraints,'objective_weights',ow, ...
               'risk_tolerance',risk);
    if isempty(P); P = s; else; P(end+1) = s; end
end
